"""Write ANSWERS/<n>/ANSWER.md, REASONING.md, trace.json, result.json."""
from __future__ import annotations

import json
from pathlib import Path

DECISION_LABEL = {
    "act": "ACT — route the request to the party with authority",
    "request_information": "REQUEST INFORMATION — ask the right party for what is missing",
    "escalate_to_human": "ESCALATE TO HUMAN — hand over with full context",
    "hold_no_action": "HOLD — no action now (deliberate)",
    "decline": "DECLINE — request cannot be fulfilled as asked",
}


def _q(text: str) -> str:
    return "\n".join("> " + line if line.strip() else ">" for line in (text or "").splitlines()) or "> (empty)"


def _bullets(items, empty="None.") -> str:
    items = [i for i in (items or []) if str(i).strip()]
    return "\n".join(f"- {i}" for i in items) if items else empty


def answer_md(res: dict) -> str:
    p = res["plan"]
    out = [f"# Case {res['answer_id']} — {res['title']}", ""]
    out += [f"**Decision:** {DECISION_LABEL.get(p.get('decision_type'), p.get('decision_type'))}", "",
            f"**In one line:** {p.get('decision_summary', '')}", "",
            f"**Final result:** {res['final_status']}", ""]
    if not res.get("approved", True):
        out += ["**Note:** the independent reviewer did not approve an autonomous action, so the case was handed to a human "
                "with the drafted actions (not sent). See REASONING.md.", ""]
    out += ["## What the system received", "", *_received_lines(res), ""]
    if (p.get("direct_answer") or "").strip():
        out += ["## Direct answer", "", p["direct_answer"].strip(), ""]
    out += ["## Actions taken", ""]
    if not res["executed"]:
        out += ["No outbound action (deliberate). " + (p.get("follow_up") or ""), ""]
    for e in res["executed"]:
        a = e["action"]
        tool = a.get("tool")
        status = e["status"].upper()
        e = dict(e, index=(e["index"] + 1) if isinstance(e["index"], int) else e["index"])
        ref = ""
        if e.get("result"):
            ref = e["result"].get("message_id") or e["result"].get("ticket_id") or e["result"].get("follow_up_id") or e["result"].get("note_id") or ""
        if tool == "send_message":
            out.append(f"{e['index']}. **send_message** → {a.get('to_name', '')} ({a.get('to_role', '')}) via *{a.get('channel', '')}* — {status} {ref}")
            if a.get("subject"):
                out.append(f"   - Subject: {a['subject']}")
            out.append("")
            out.append(_q(a.get("body", "")))
        elif tool == "escalate_to_human":
            body = (e.get("result") or {}).get("handover") or a.get("body", "")
            out.append(f"{e['index']}. **escalate_to_human** → {a.get('to_name') or 'Desk supervisor'} (priority {a.get('priority', 'normal')}) — {status} {ref}")
            out.append("")
            out.append(_q(a.get("body", body)))
        elif tool == "schedule_follow_up":
            out.append(f"{e['index']}. **schedule_follow_up** at {a.get('when', '')} — {status} {ref}: {a.get('body', '')}")
        else:
            out.append(f"{e['index']}. **{tool}** — {status} {ref}: {a.get('body', '')}")
        if e.get("error"):
            out.append(f"   - Error: {e['error']} (attempts: {e['attempts']})")
        out.append("")
    escal = [e for e in res["executed"] if e["action"].get("tool") == "escalate_to_human" and e["status"] == "done"]
    out += ["## What was escalated", "", _bullets(
        [f"{(e.get('result') or {}).get('ticket_id', '')} to {e['action'].get('to_name') or 'Desk supervisor'} "
         f"(priority {e['action'].get('priority', 'normal')}): {e['action'].get('subject') or e['action'].get('purpose') or ''}".strip()
         for e in escal], "Nothing was escalated to a human."), ""]
    failed = [e for e in res["executed"] if e["status"] == "failed"]
    fail_lines = [f"Action {e['index'] + 1 if isinstance(e['index'], int) else e['index']} ({e['action'].get('tool')} to "
                  f"{e['action'].get('to_name') or e['action'].get('to_role') or '?'}): {e.get('error')} - handed to a human with the exact draft"
                  for e in failed]
    if not res.get("approved", True):
        fail_lines.append("The plan was not approved by the independent reviewer; drafted messages were not sent.")
    fail_lines += [f"Input problem: {w}" for w in res.get("warnings") or [] if "attachment" in w or "could not" in w]
    out += ["## What failed", "", _bullets(fail_lines, "Nothing failed."), ""]
    out += ["## Deliberately not done", "", _bullets(p.get("not_doing")), ""]
    out += ["## What closes this step", "", p.get("closes_when", "") or "n/a", ""]
    out += ["## Follow-up", "", p.get("follow_up", "") or "n/a", ""]
    if (p.get("human_handover_notes") or "").strip() and p.get("decision_type") != "escalate_to_human":
        out += ["## Notes for a human", "", p["human_handover_notes"].strip(), ""]
    out += [f"_Confidence: {p.get('confidence', '?')} · generated by delivery-desk-agent · models: {', '.join(res.get('models_used') or [])}_", ""]
    return "\n".join(out)


def _received_lines(res: dict) -> list:
    inp = res.get("inputs") or {}
    lines = [f"- Case `{res['case_id']}` (track: {res.get('track', '')}); files: {', '.join(inp.get('files') or []) or 'none'}",
             f"- Attachments: {', '.join(inp.get('attachments') or []) or 'none'}"]
    if inp.get("events") is not None:
        lines.append(f"- {inp['events']} dated events; latest at {inp.get('now') or 'unknown'} (decision made as of then)")
    if res.get("warnings"):
        lines.append(f"- Input warnings: {'; '.join(res['warnings'])}")
    return lines


def reasoning_md(res: dict) -> str:
    p = res["plan"]
    pre = res.get("pre_handover_plan") or p
    inp = res["inputs"]
    out = [f"# Case {res['answer_id']} — reasoning", ""]
    out += ["## What the system received", "",
            f"- Case folder: `{res['case_id']}` (track: {res['track']}, mode: {res['mode']})",
            f"- Files read: {', '.join(inp.get('files') or []) or 'none'}",
            f"- Attachments read: {', '.join(inp.get('attachments') or []) or 'none'}"]
    if inp.get("hidden_events"):
        out.append(f"- Hidden for evaluation (after escalation point): events {inp['hidden_events']}, attachments {inp.get('hidden_attachments')}")
    if res.get("warnings"):
        out.append("- Loader warnings: " + "; ".join(res["warnings"]))
    out += ["", "## Situation", "", pre.get("situation", ""), ""]
    out += ["## Facts", "", "| Fact | Source | Status |", "|---|---|---|"]
    for f in pre.get("facts") or []:
        out.append(f"| {str(f.get('fact', '')).replace('|', '/')} | {f.get('source', '')} | {f.get('status', '')} |")
    out += ["", "## Conflicts", "", _bullets(pre.get("conflicts")), "",
            "## Missing information", "", _bullets(pre.get("missing_information")), "",
            "## Risk flags", "", _bullets(pre.get("risk_flags")), "",
            "## Who controls what", ""]
    out += [f"- **{a.get('party')}** — {a.get('controls')}" for a in pre.get("authority_map") or []] or ["None identified."]
    out += ["", "## Decision and rationale", "",
            f"**{DECISION_LABEL.get(pre.get('decision_type'), pre.get('decision_type'))}** — {pre.get('decision_summary', '')}", "",
            pre.get("rationale", ""), ""]
    alts = pre.get("alternatives_rejected") or []
    if alts:
        out += ["### Alternatives rejected", ""] + [f"- {a.get('option')}: {a.get('why_not')}" for a in alts] + [""]
    out += ["## Independent review (before anything was sent)", ""]
    for r in res.get("review_rounds") or []:
        rv = r.get("review")
        out.append(f"### Round {r['round']} — planner decision: {r.get('plan_decision')}")
        if r.get("lint"):
            out.append("Automated policy lint:")
            out += [f"- [{l['level']}] action {l.get('action_index')}: {l['rule']} '{l.get('match', '')}'"
                    + (" (negated context)" if l.get("negated_context") else "") for l in r["lint"]]
        else:
            out.append("Automated policy lint: no findings.")
        if rv:
            out.append(f"Reviewer verdict: **{rv.get('verdict')}** — {rv.get('summary', '')}")
            failed_checks = [k for k, v in (rv.get("checks") or {}).items() if v is False]
            if failed_checks:
                out.append("Failed checks: " + ", ".join(failed_checks))
            out += [f"- [{i.get('severity')}] action {i.get('action_index')}: {i.get('problem')} → fix: {i.get('fix')}" for i in rv.get("issues") or []]
        out.append("")
    if not res.get("approved", True):
        out += ["**Outcome of review:** not approved → converted to human handover; drafted messages were NOT sent.", ""]
    out += ["## Execution log", ""]
    for e in res["executed"]:
        a = e["action"]
        line = f"- {e['index']}: `{a.get('tool')}` → {e['status']} after {e['attempts']} attempt(s)"
        if e.get("result"):
            line += f" — {json.dumps({k: v for k, v in e['result'].items() if k != 'handover'})}"
        if e.get("error"):
            line += f" — ERROR: {e['error']}"
        if e.get("recovered_after"):
            line += f" — recovered after transient error(s): {'; '.join(e['recovered_after'])}"
        out.append(line)
    if not res["executed"]:
        out.append("- No tool calls (hold / no action).")
    failed = [e for e in res["executed"] if e["status"] == "failed"]
    out += ["", "## What failed", "", _bullets([f"action {e['index']} ({e['action'].get('tool')}): {e.get('error')}" for e in failed],
                                                 "Nothing failed during execution."), ""]
    calcs = [t for t in res["trace"] if t.get("type") == "tool_call" and t.get("tool") == "calculate"]
    if calcs:
        out += ["## Calculations", ""] + [f"- {c['input'].get('label', '')}: `{c['input'].get('expression')}` = {c['output'].get('result', c['output'].get('error'))}" for c in calcs] + [""]
    u = res.get("usage") or {}
    out += ["## Run metadata", "",
            f"- Models: {', '.join(res.get('models_used') or [])}; LLM calls: {u.get('calls')}; tokens in/out: {u.get('input_tokens')}/{u.get('output_tokens')}",
            f"- Elapsed: {res.get('elapsed_s')} s; full trace: `trace.json`", ""]
    return "\n".join(out)


def failure_md(case_id: str, answer_id: str, title: str, error: str, trace_note: str = "") -> str:
    return "\n".join([
        f"# Case {answer_id} — {title}", "",
        "**Decision:** SYSTEM FAILURE — no automated decision was produced.", "",
        f"The agent could not complete this case: `{error}`.", "",
        "**Safe default:** no message was sent to any customer or third party. The case must be handled by a human coordinator.",
        trace_note, ""])


def write_case(out_dir: Path, res: dict) -> Path:
    d = out_dir / str(res["answer_id"])
    d.mkdir(parents=True, exist_ok=True)
    (d / "ANSWER.md").write_text(answer_md(res), encoding="utf-8")
    (d / "REASONING.md").write_text(reasoning_md(res), encoding="utf-8")
    (d / "trace.json").write_text(json.dumps(res["trace"], indent=1, ensure_ascii=False, default=str), encoding="utf-8")
    slim = {k: v for k, v in res.items() if k != "trace"}
    (d / "result.json").write_text(json.dumps(slim, indent=1, ensure_ascii=False, default=str), encoding="utf-8")
    return d


def write_failure(out_dir: Path, case_id: str, answer_id: str, title: str, error: str, trace: list) -> Path:
    d = out_dir / str(answer_id)
    d.mkdir(parents=True, exist_ok=True)
    (d / "ANSWER.md").write_text(failure_md(case_id, answer_id, title, error), encoding="utf-8")
    (d / "REASONING.md").write_text(f"# Case {answer_id} — reasoning\n\nThe run failed before a decision was made.\n\n"
                                    f"Error: `{error}`\n\nSee trace.json for the calls made before the failure.\n", encoding="utf-8")
    (d / "trace.json").write_text(json.dumps(trace, indent=1, ensure_ascii=False, default=str), encoding="utf-8")
    return d
